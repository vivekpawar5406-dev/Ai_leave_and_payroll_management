CREATE TABLE IF NOT EXISTS employees (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(120) NOT NULL, email VARCHAR(160) NOT NULL UNIQUE,
 department VARCHAR(100) NOT NULL, job_title VARCHAR(120) DEFAULT 'Employee', base_salary DECIMAL(12,2) NOT NULL DEFAULT 0,
 leave_balance INT NOT NULL DEFAULT 12, status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS leave_requests (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, employee_id BIGINT NOT NULL, leave_type VARCHAR(30) NOT NULL,
 start_date DATE NOT NULL, end_date DATE NOT NULL, days INT NOT NULL, reason VARCHAR(500), status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, CONSTRAINT fk_leave_employee FOREIGN KEY(employee_id) REFERENCES employees(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS attendance (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, employee_id BIGINT NOT NULL, work_date DATE NOT NULL, status VARCHAR(20) NOT NULL,
 hours DECIMAL(4,1) NOT NULL DEFAULT 0, UNIQUE KEY uq_attendance_day(employee_id,work_date),
 CONSTRAINT fk_attendance_employee FOREIGN KEY(employee_id) REFERENCES employees(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS payroll (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, employee_id BIGINT NOT NULL, pay_month VARCHAR(7) NOT NULL,
 basic_salary DECIMAL(12,2) NOT NULL, allowance DECIMAL(12,2) NOT NULL DEFAULT 0, deduction DECIMAL(12,2) NOT NULL DEFAULT 0,
 tax DECIMAL(12,2) NOT NULL DEFAULT 0, net_salary DECIMAL(12,2) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, UNIQUE KEY uq_payroll_month(employee_id,pay_month),
 CONSTRAINT fk_payroll_employee FOREIGN KEY(employee_id) REFERENCES employees(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS users (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  username VARCHAR(100) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(50) NOT NULL DEFAULT 'EMPLOYEE',
  display_name VARCHAR(120) NOT NULL,
  employee_id BIGINT,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_user_employee FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE SET NULL
);
